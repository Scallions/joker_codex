import {
  CATALOG_CONTENT_VERSION,
  type CatalogOperation,
  type JokerCatalogRow,
  type JokerCopyPolicy,
  type JokerEnsemble,
  type JokerPredicate,
  type JokerRarity,
  type JokerValue,
} from '../schema/catalog';

interface JokerSource {
  readonly ordinal: number;
  readonly name: string;
  readonly description: string;
  readonly flavor: string;
  readonly rarity: JokerRarity;
  readonly cost: number;
  readonly ensemble: JokerEnsemble;
  readonly copyPolicy: JokerCopyPolicy;
  readonly permanentEligible?: boolean;
  readonly perishableEligible?: boolean;
  readonly initialAbilityState?: Readonly<Record<string, string | number | boolean>>;
  readonly availability?: JokerCatalogRow['availability'];
  readonly externalDependencyIds?: readonly string[];
  readonly trigger: JokerCatalogRow['effects'][number]['trigger'];
  readonly operations: readonly CatalogOperation[];
  readonly additionalEffects?: readonly {
    readonly trigger: JokerCatalogRow['effects'][number]['trigger'];
    readonly operations: readonly CatalogOperation[];
  }[];
}

function threeDigit(value: number): string {
  return value.toString().padStart(3, '0');
}

function defineJoker(source: JokerSource): JokerCatalogRow {
  const ordinal = threeDigit(source.ordinal);
  const id = `bxqp:joker:${ordinal}`;
  return {
    id,
    family: 'joker',
    ordinal: source.ordinal,
    referenceIndex: `J${ordinal}`,
    nameKey: `${id}.name`,
    descriptionKey: `${id}.description`,
    flavorKey: `${id}.flavor`,
    assetId: `bxqp:asset:joker:${ordinal}`,
    ownershipId: `bxqp:ownership:joker:${ordinal}`,
    introducedIn: CATALOG_CONTENT_VERSION,
    availability: source.availability ?? { kind: 'always', value: null },
    unlockObjectiveId: null,
    discovery: { kind: 'first-acquisition', value: null },
    cost: source.cost,
    weightUnits: 1,
    prerequisiteIds: [],
    externalDependencyIds: source.externalDependencyIds ?? [],
    contractIds: [
      `contract:joker:j${ordinal}:positive`,
      `contract:joker:j${ordinal}:boundary`,
      `contract:joker:j${ordinal}:debuffed`,
    ],
    effects: [
      { trigger: source.trigger, operations: source.operations },
      ...(source.additionalEffects ?? []),
    ].map((effect, index) => ({
      id: `bxqp:effect:joker:${ordinal}:${index + 1}`,
      handlerId: 'bxqp:handler:catalog-operations',
      trigger: effect.trigger,
      priority: index,
      operations: effect.operations,
    })),
    mechanicalProfileId: null,
    rarity: source.rarity,
    ensemble: source.ensemble,
    copyPolicy: source.copyPolicy,
    stickerEligibility: {
      permanent: source.permanentEligible ?? true,
      perishable: source.perishableEligible ?? true,
      rental: true,
    },
    initialAbilityState: source.initialAbilityState ?? {},
  };
}

function jokerScore(
  metric: Extract<CatalogOperation, { type: 'joker-score' }>['metric'],
  predicate: JokerPredicate,
  value: JokerValue,
  copyFacet: Extract<CatalogOperation, { type: 'joker-score' }>['copyFacet'] = 'output',
): CatalogOperation {
  return { type: 'joker-score', metric, predicate, value, copyFacet };
}

function fixedScore(
  metric: Extract<CatalogOperation, { type: 'joker-score' }>['metric'],
  value: number,
  predicate: JokerPredicate = { kind: 'always' },
): CatalogOperation {
  return jokerScore(metric, predicate, { kind: 'fixed', value });
}

