import type {
  CatalogOperation,
  JokerCopyFacet,
  JokerPredicate,
  JokerValue,
} from '../schema/catalog';
import type { JokerSource } from './jokers';

const FINAL_CATALOG_VERSION = 'joker-catalog-3' as const;

interface JokerSourceV6 extends JokerSource {
  readonly namedFixture: string;
  readonly art: {
    readonly focalKey: string;
    readonly prompt: string;
    readonly provenancePath: string;
  };
}

const ALWAYS = { kind: 'always' } as const satisfies JokerPredicate;

function score(
  metric: Extract<CatalogOperation, { type: 'joker-score' }>['metric'],
  value: JokerValue,
  predicate: JokerPredicate = ALWAYS,
  copyFacet: JokerCopyFacet = 'output',
): CatalogOperation {
  return { type: 'joker-score', metric, predicate, value, copyFacet };
}

function fixedScore(
  metric: Extract<CatalogOperation, { type: 'joker-score' }>['metric'],
  value: number,
  predicate: JokerPredicate = ALWAYS,
  copyFacet: JokerCopyFacet = 'output',
): CatalogOperation {
  return score(metric, { kind: 'fixed', value }, predicate, copyFacet);
}

function passive(
  capability: Extract<
    CatalogOperation,
    { type: 'joker-passive-capability' }
  >['capability'],
  value: number,
): CatalogOperation {
  return {
    type: 'joker-passive-capability',
    capability,
    value: { kind: 'fixed', value },
    copyFacet: 'none',
  };
}

function stateChange(
  key: string,
  mode: 'set' | 'add' | 'decrement',
  value: JokerValue,
  predicate: JokerPredicate = ALWAYS,
): CatalogOperation {
  return {
    type: 'joker-state-change',
    key,
    mode,
    value,
    predicate,
    copyFacet: 'none',
  };
}

function stateChangeClamped(
  key: string,
  mode: 'set' | 'add',
  value: JokerValue,
  minimum: number | null,
  maximum: number | null,
  predicate: JokerPredicate = ALWAYS,
): CatalogOperation {
  return {
    type: 'joker-state-change-clamped',
    key,
    mode,
    value,
    minimum,
    maximum,
    destroyAtOrBelow: null,
    predicate,
    copyFacet: 'none',
  };
}

function action(
  actionName: Extract<CatalogOperation, { type: 'joker-runtime-action' }>['action'],
  parameters: Readonly<Record<string, string | number | boolean | null>> = {},
  predicate: JokerPredicate = ALWAYS,
  copyFacet: JokerCopyFacet = 'none',
): CatalogOperation {
  return {
    type: 'joker-runtime-action',
    action: actionName,
    predicate,
    parameters,
    copyFacet,
  };
}

function art(ordinal: number, focalKey: string, prompt: string): JokerSourceV6['art'] {
  return {
    focalKey,
    prompt,
    provenancePath: `/assets/jokers/provenance/${ordinal.toString().padStart(3, '0')}.md`,
  };
}

